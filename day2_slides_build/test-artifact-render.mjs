import fs from "node:fs/promises";
import { Presentation } from "file:///C:/Users/CJSCOPE/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/@oai/artifact-tool/dist/artifact_tool.mjs";
const presentation = Presentation.create({ slideSize: { width: 1280, height: 720 } });
const slide = presentation.slides.add();
slide.background.fill = "#FFFFFF";
const box = slide.shapes.add({ geometry: "textbox", position: { left: 80, top: 80, width: 500, height: 100 }, fill: "none", line: { style: "solid", fill: "none", width: 0 } });
box.text = "test";
box.text.style = { fontSize: 40, color: "#111111" };
console.log("before png");
const png = await presentation.export({ slide, format: "png", scale: 1 });
await fs.writeFile("C:/Users/CJSCOPE/Desktop/PythonSDD/day2_slides_build/test-artifact.png", new Uint8Array(await png.arrayBuffer()));
